// merge-chapters.js — Bundle all chapter sources into one annotated file.
// Run:  node tools/merge-chapters.js
// Reads src/chapters/*/  (all .js files in each chapter dir),
// sorts chapter dirs by trailing numeric suffix (chapter-01 < chapter-10),
// writes dist/merge/chapters.js with stable boundary markers.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const CHAPTERS_DIR = path.join(ROOT, "src", "chapters");
const OUT_DIR = path.join(ROOT, "dist", "merge");

function sortKey(name) {
  // Prologue first, then chapter-NNN sorted numerically (chapter-01 < chapter-10).
  if (name.toLowerCase().includes("prologue") || name.toLowerCase().includes("intro")) return -1;
  const m = name.match(/(\d+)/);
  return m ? Number(m[1]) : Number.POSITIVE_INFINITY;
}

async function main() {
  const dirs = fs
    .readdirSync(CHAPTERS_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort((a, b) => sortKey(a) - sortKey(b));

  if (dirs.length === 0) {
    console.error("No chapter directories found under", CHAPTERS_DIR);
    process.exit(1);
  }

  const lines = [];
  lines.push("// Auto-generated by tools/merge-chapters.js — do not edit by hand.");
  lines.push(`// Chapters: ${dirs.join(", ")}`);
  lines.push(`// Generated: ${new Date().toISOString()}`);
  lines.push("");

  let totalFiles = 0;
  for (const dir of dirs) {
    const chapterDir = path.join(CHAPTERS_DIR, dir);
    const files = fs
      .readdirSync(chapterDir)
      .filter((f) => f.endsWith(".js"))
      .sort();
    totalFiles += files.length;

    lines.push("// ".repeat(20));
    lines.push(`// === CHAPTER ${dir} ===`);
    lines.push("// ".repeat(20));
    lines.push("");

    for (const file of files) {
      const fullPath = path.join(chapterDir, file);
      const rel = path.relative(ROOT, fullPath).replace(/\\/g, "/");
      lines.push(`// --- FILE: ${rel} ---`);
      lines.push("");
      const content = fs.readFileSync(fullPath, "utf-8");
      lines.push(content.trimEnd());
      lines.push("");
      lines.push("");
    }
  }

  const output = lines.join("\n");
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const outFile = path.join(OUT_DIR, "chapters.js");
  fs.writeFileSync(outFile, output, "utf-8");

  console.log(`Merged ${dirs.length} chapter(s), ${totalFiles} file(s) → ${path.relative(ROOT, outFile)}`);
  console.log(`  Size: ${(Buffer.byteLength(output) / 1024).toFixed(1)} kB`);
}

main().catch((e) => { console.error(e); process.exit(1); });
